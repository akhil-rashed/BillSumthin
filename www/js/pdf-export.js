function sanitizePdfText(str) {
  // Standard PDF Type1 Helvetica supports ASCII cleanly; transliterate common symbols
  return String(str ?? '')
    .replace(/৳/g, 'BDT ')
    .replace(/₹/g, 'INR ')
    .replace(/€/g, 'EUR ')
    .replace(/£/g, 'GBP ')
    .replace(/[^\x20-\x7E]/g, ' ')
    .replace(/\\/g, '\\\\')
    .replace(/\(/g, '\\(')
    .replace(/\)/g, '\\)');
}

function buildMultiPagePdfBytes(lines) {
  const pageWidth = 595;
  const pageHeight = 842;
  const marginX = 48;
  const startY = 770;
  const minY = 64;
  const lineHeight = 16;

  const pages = [];
  let currentOps = [];
  let y = startY;

  const pushHeader = () => {
    currentOps.push('0.145 0.388 0.922 rg');
    currentOps.push(`BT /F2 18 Tf ${marginX} 798 Td (BillSumthin) Tj ET`);
    currentOps.push('0.42 0.45 0.50 rg');
    currentOps.push(`BT /F1 10 Tf ${marginX + 112} 799 Td (Understand Any Bill) Tj ET`);
    currentOps.push('0.89 0.91 0.92 RG 1 w 48 786 m 547 786 l S');
    currentOps.push('0.067 0.075 0.094 rg');
  };

  pushHeader();

  for (const item of lines) {
    if (y < minY) {
      pages.push(currentOps);
      currentOps = [];
      y = startY;
      pushHeader();
    }
    const font = item.bold ? '/F2' : '/F1';
    const size = item.size || 11;
    const text = sanitizePdfText(item.text);
    currentOps.push(`BT ${font} ${size} Tf ${marginX} ${y} Td (${text}) Tj ET`);
    y -= item.gap || lineHeight;
  }
  pages.push(currentOps);

  const totalPages = pages.length;
  const objects = [];
  const addObj = (body) => {
    objects.push(body);
    return objects.length;
  };

  const catalogId = addObj('');
  const pagesId = addObj('');
  const fontRegularId = addObj('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>');
  const fontBoldId = addObj('<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica-Bold >>');

  const pageIds = [];
  pages.forEach((ops, idx) => {
    const footer = [
      '0.42 0.45 0.50 rg',
      '0.89 0.91 0.92 RG 0.8 w 48 48 m 547 48 l S',
      `BT /F1 9 Tf 48 34 Td (Generated by BillSumthin - Understand Any Bill) Tj ET`,
      `BT /F1 9 Tf 485 34 Td (Page ${idx + 1} of ${totalPages}) Tj ET`
    ];
    const stream = [...ops, ...footer].join('\n');
    const contentId = addObj(`<< /Length ${stream.length} >>\nstream\n${stream}\nendstream`);
    const pageId = addObj(
      `<< /Type /Page /Parent ${pagesId} 0 R /MediaBox [0 0 ${pageWidth} ${pageHeight}] /Resources << /Font << /F1 ${fontRegularId} 0 R /F2 ${fontBoldId} 0 R >> >> /Contents ${contentId} 0 R >>`
    );
    pageIds.push(pageId);
  });

  objects[catalogId - 1] = `<< /Type /Catalog /Pages ${pagesId} 0 R >>`;
  objects[pagesId - 1] = `<< /Type /Pages /Kids [${pageIds.map((id) => `${id} 0 R`).join(' ')}] /Count ${pageIds.length} >>`;

  let pdf = '%PDF-1.4\n';
  const offsets = [0];
  objects.forEach((obj, i) => {
    offsets.push(pdf.length);
    pdf += `${i + 1} 0 obj\n${obj}\nendobj\n`;
  });

  const xrefPos = pdf.length;
  pdf += `xref\n0 ${objects.length + 1}\n0000000000 65535 f \n`;
  for (let i = 1; i <= objects.length; i++) {
    pdf += `${String(offsets[i]).padStart(10, '0')} 00000 n \n`;
  }
  pdf += `trailer\n<< /Size ${objects.length + 1} /Root ${catalogId} 0 R >>\nstartxref\n${xrefPos}\n%%EOF`;

  return btoa(unescape(encodeURIComponent(pdf)));
}

export async function exportBillAsPdf(bill) {
  const cur = bill.currencyCode || 'BDT';
  const sym = bill.currencySymbol || '';
  const cat = getCategoryMeta(bill.category);

  const lines = [
    { text: formatBillTypeLabel(bill.documentType), bold: true, size: 16, gap: 22 },
    { text: `Provider: ${bill.provider || 'Not detected'}`, bold: true, size: 12, gap: 18 },
    { text: `Total: ${formatMoney(bill.total, cur, sym)}`, bold: true, size: 14, gap: 20 },
    { text: `Amount Due: ${formatMoney(bill.amountDue, cur, sym)}`, gap: 16 },
    { text: `Category: ${cat.name}`, gap: 16 },
    { text: `Issue Date: ${bill.issueDate || 'Not detected'}   |   Due Date: ${bill.dueDate || 'Not detected'}`, gap: 16 },
    { text: `Currency: ${cur}`, gap: 22 },
    { text: 'BREAKDOWN', bold: true, size: 12, gap: 18 }
  ];

  if (bill.items && bill.items.length) {
    for (const item of bill.items) {
      lines.push({ text: `- ${item.name}: ${formatMoney(item.amount, cur, sym)}`, gap: 15 });
    }
  } else {
    lines.push({ text: '- No itemized lines detected', gap: 15 });
  }

  if (bill.tax != null) lines.push({ text: `Tax / VAT: ${formatMoney(bill.tax, cur, sym)}`, gap: 15 });
  if (bill.fees != null) lines.push({ text: `Fees / Service Charge: ${formatMoney(bill.fees, cur, sym)}`, gap: 15 });
  if (bill.discounts != null) lines.push({ text: `Discounts: -${formatMoney(bill.discounts, cur, sym)}`, gap: 15 });

  lines.push({ text: '', gap: 10 });
  lines.push({ text: 'INSIGHTS & HISTORY', bold: true, size: 12, gap: 18 });
  if (bill.suspiciousChange) {
    lines.push({
      text: `Suspicious Change: ${bill.suspiciousChange.roundedPercent}% ${bill.suspiciousChange.direction} (Previous: ${formatMoney(bill.suspiciousChange.previousTotal, cur, sym)})`,
      gap: 16
    });
  }
  if (bill.recurring) {
    lines.push({ text: `Recurring Expense: Around ${formatMoney(bill.recurringEstimate || bill.total, cur, sym)}/month`, gap: 16 });
  }
  if (bill.priceHistory && bill.priceHistory.length) {
    for (const ph of bill.priceHistory) {
      lines.push({
        text: `Price History (${ph.itemName}): Latest ${formatMoney(ph.latestPrice, cur, sym)}/${ph.unit} | Avg ${formatMoney(ph.averagePrice, cur, sym)}`,
        gap: 15
      });
    }
  }
  lines.push({ text: `Analysis Confidence: ${Math.round((bill.confidence || 0.75) * 100)}%`, gap: 16 });

  const base64Pdf = buildMultiPagePdfBytes(lines);
  const fileName = `BillSumthin-${(bill.provider || 'bill').replace(/[^a-z0-9]+/gi, '_')}.pdf`;

  if (isCapacitorNative()) {
    const exporter = getPlugin('NativeFileExport');
    if (exporter?.saveAndShare) {
      try {
        return await exporter.saveAndShare({
          fileName,
          mimeType: 'application/pdf',
          base64Data: base64Pdf
        });
      } catch {
        return { ok: false, error: 'Could not save PDF to device storage.' };
      }
    }
  }

  // Web download fallback
  const binary = atob(base64Pdf);
  const bytes = new Uint8Array(binary.length);
  for (let i = 0; i < binary.length; i++) bytes[i] = binary.charCodeAt(i);
  const blob = new Blob([bytes], { type: 'application/pdf' });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = fileName;
  a.click();
  setTimeout(() => URL.revokeObjectURL(url), 2000);
  return { ok: true, fileName };
}
